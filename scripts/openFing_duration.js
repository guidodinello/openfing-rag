const https = require('https');
const fs = require('fs');
const { exec } = require('child_process');
const { promisify } = require('util');

const execAsync = promisify(exec);

// Configuration
const CONFIG = {
  LOG_FILE: 'video_durations.json',
  REQUEST_TIMEOUT: 15000,
  REQUEST_DELAY: 200,
  BITRATE_ESTIMATE: 1000000, // 1 Mbps for duration estimation
  USER_AGENT: 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36'
};

// State management
class VideoCache {
  constructor() {
    this.cache = new Map();
  }

  load() {
    try {
      if (fs.existsSync(CONFIG.LOG_FILE)) {
        const data = fs.readFileSync(CONFIG.LOG_FILE, 'utf8');
        const parsed = JSON.parse(data);
        for (const [url, duration] of Object.entries(parsed)) {
          this.cache.set(url, duration);
        }
        console.log(`Loaded ${Object.keys(parsed).length} existing entries from log file`);
      }
    } catch (error) {
      console.log(`Error loading existing data: ${error.message}`);
    }
  }

  get(url) {
    return this.cache.get(url);
  }

  set(url, duration) {
    this.cache.set(url, duration);
  }

  save() {
    try {
      const dataToSave = Object.fromEntries(this.cache);
      fs.writeFileSync(CONFIG.LOG_FILE, JSON.stringify(dataToSave, null, 2));
    } catch (error) {
      console.log(`Error saving to log file: ${error.message}`);
    }
  }
}

// URL validation utilities
function isYouTubeUrl(url) {
  return url.includes('youtube.com') || url.includes('youtu.be');
}

function extractYouTubeVideoId(url) {
  const match = url.match(/(?:youtube\.com\/(?:[^\/]+\/.+\/|(?:v|e(?:mbed)?)\/|.*[?&]v=)|youtu\.be\/)([^"&?\/\s]{11})/i);
  return match?.[1] || null;
}

// HTTP utilities
function makeHttpRequest(url, options = {}) {
  return new Promise((resolve, reject) => {
    const req = https.request(new URL(url), options, (res) => {
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => resolve({ response: res, data }));
    });

    req.on('error', reject);
    req.setTimeout(CONFIG.REQUEST_TIMEOUT, () => {
      req.destroy();
      reject(new Error('Request timeout'));
    });

    req.end();
  });
}

function makeHeadRequest(url) {
  return makeHttpRequest(url, { method: 'HEAD' });
}

function makeGetRequest(url, headers = {}) {
  return makeHttpRequest(url, { 
    method: 'GET', 
    headers: { 'User-Agent': CONFIG.USER_AGENT, ...headers }
  });
}

// Duration parsing utilities
function parseYouTubeDuration(htmlContent) {
  const patterns = [
    /"lengthSeconds":"(\d+)"/,
    /"duration":"(\d+)"/,
    /"approxDurationMs":"(\d+)"/,
    /contentLength":\s*"(\d+)"/
  ];

  for (const pattern of patterns) {
    const match = htmlContent.match(pattern);
    if (match) {
      const value = parseInt(match[1]);
      // Convert milliseconds to seconds if needed
      return pattern.source.includes('approxDurationMs') ? value / 1000 : value;
    }
  }
  return null;
}

function estimateDurationFromFileSize(contentLength) {
  if (!contentLength) return null;
  return (contentLength * 8) / CONFIG.BITRATE_ESTIMATE; // seconds
}

function checkVideoAvailability(htmlContent) {
  return !(htmlContent.includes('Video unavailable') || htmlContent.includes('Private video'));
}

// Video metadata extraction utilities
async function extractDurationWithFFProbe(url) {
  try {
    const command = `ffprobe -v quiet -show_entries format=duration -of csv=p=0 "${url}"`;
    const { stdout } = await execAsync(command);
    const duration = parseFloat(stdout.trim());
    
    if (isNaN(duration) || duration <= 0) {
      throw new Error('Invalid duration from ffprobe');
    }
    
    return duration; // seconds
  } catch (error) {
    throw new Error(`FFProbe extraction failed: ${error.message}`);
  }
}

async function extractDurationWithFFMpeg(url) {
  try {
    const command = `ffmpeg -i "${url}" -f null - 2>&1 | grep "Duration"`;
    const { stdout, stderr } = await execAsync(command);
    const output = stdout + stderr;
    
    const durationMatch = output.match(/Duration: (\d{2}):(\d{2}):(\d{2}\.\d{2})/);
    if (!durationMatch) {
      throw new Error('Duration not found in ffmpeg output');
    }
    
    const [, hours, minutes, seconds] = durationMatch;
    const totalSeconds = parseInt(hours) * 3600 + parseInt(minutes) * 60 + parseFloat(seconds);
    
    return totalSeconds;
  } catch (error) {
    throw new Error(`FFMpeg extraction failed: ${error.message}`);
  }
}

async function downloadVideoSample(url, sampleSizeMB = 5) {
  const tempFile = `temp_sample_${Date.now()}.mp4`;
  
  try {
    // Download first N MB of the file
    const sampleBytes = sampleSizeMB * 1024 * 1024;
    const command = `curl -r 0-${sampleBytes} "${url}" -o ${tempFile}`;
    await execAsync(command);
    
    return tempFile;
  } catch (error) {
    // Clean up on error
    if (fs.existsSync(tempFile)) {
      fs.unlinkSync(tempFile);
    }
    throw new Error(`Sample download failed: ${error.message}`);
  }
}

async function extractDurationFromSample(url) {
  let tempFile = null;
  
  try {
    // Download a sample of the video
    tempFile = await downloadVideoSample(url);
    
    // Try to extract duration from the sample
    const command = `ffprobe -v quiet -show_entries format=duration -of csv=p=0 "${tempFile}"`;
    const { stdout } = await execAsync(command);
    const duration = parseFloat(stdout.trim());
    
    if (isNaN(duration) || duration <= 0) {
      throw new Error('Could not extract duration from sample');
    }
    
    return duration; // seconds
  } finally {
    // Clean up temp file
    if (tempFile && fs.existsSync(tempFile)) {
      fs.unlinkSync(tempFile);
    }
  }
}

// Duration retrieval services
async function getYouTubeDuration(url) {
  const videoId = extractYouTubeVideoId(url);
  if (!videoId) {
    throw new Error('Invalid YouTube URL');
  }

  try {
    const { data } = await makeGetRequest(`https://www.youtube.com/watch?v=${videoId}`);
    
    if (!checkVideoAvailability(data)) {
      throw new Error('Video unavailable/private');
    }

    const duration = parseYouTubeDuration(data);
    if (!duration || duration <= 0) {
      throw new Error('No duration found');
    }

    return duration / 60; // Convert to minutes
  } catch (error) {
    throw new Error(`YouTube processing failed: ${error.message}`);
  }
}

async function getGenericVideoDuration(url) {
  // Try multiple methods in order of preference
  const methods = [
    { name: 'FFProbe Direct', fn: () => extractDurationWithFFProbe(url) },
    { name: 'FFMpeg Direct', fn: () => extractDurationWithFFMpeg(url) },
    { name: 'Sample Analysis', fn: () => extractDurationFromSample(url) }
  ];

  for (const method of methods) {
    try {
      console.log(`  Trying ${method.name}...`);
      const durationSeconds = await method.fn();
      console.log(`  ✓ ${method.name} succeeded`);
      return durationSeconds / 60; // Convert to minutes
    } catch (error) {
      console.log(`  ✗ ${method.name} failed: ${error.message}`);
      continue;
    }
  }

  // Fallback to file size estimation if all methods fail
  try {
    console.log(`  Trying fallback file size estimation...`);
    const { response } = await makeHeadRequest(url);
    const contentLength = response.headers['content-length'];
    
    if (contentLength) {
      const durationSeconds = estimateDurationFromFileSize(parseInt(contentLength));
      console.log(`  ✓ File size estimation used (approximate)`);
      return durationSeconds / 60; // Convert to minutes
    }
  } catch (error) {
    // Ignore fallback errors
  }

  throw new Error('All duration extraction methods failed');
}

// Progress tracking
class ProgressTracker {
  constructor(total) {
    this.processed = 0;
    this.total = total;
    this.youtubeDuration = 0;
    this.genericDuration = 0;
  }

  logProgress(url, duration, source, error = null) {
    this.processed++;
    const prefix = `[${this.processed}/${this.total}]`;
    
    if (error) {
      console.log(`${prefix} ${url} - NOT ACCOUNTED FOR: ${error}`);
    } else if (duration !== null) {
      console.log(`${prefix} ${url} - ~${duration.toFixed(2)} minutes (${source})`);
      if (source === 'YouTube') {
        this.youtubeDuration += duration;
      } else {
        this.genericDuration += duration;
      }
    }
  }

  logCached(url, duration) {
    this.processed++;
    const prefix = `[${this.processed}/${this.total}]`;
    console.log(`${prefix} ${url} - CACHED: ~${duration.toFixed(2)} minutes`);
    
    // Add cached duration to appropriate total
    if (isYouTubeUrl(url)) {
      this.youtubeDuration += duration;
    } else {
      this.genericDuration += duration;
    }
  }

  printSummary() {
    const totalHours = (this.youtubeDuration + this.genericDuration) / 60;
    console.log(`\nSummary:`);
    console.log(`YouTube duration: ${(this.youtubeDuration / 60).toFixed(2)} hours`);
    console.log(`Generic duration: ${(this.genericDuration / 60).toFixed(2)} hours`);
    console.log(`Total duration: ${totalHours.toFixed(2)} hours`);
    console.log(`Data logged to: ${CONFIG.LOG_FILE}`);
  }
}

// Main processing logic
async function processSingleUrl(url, cache, progressTracker) {
  console.log(`Checking: ${url}`);

  // Check cache first
  const cachedDuration = cache.get(url);
  if (cachedDuration !== undefined) {
    progressTracker.logCached(url, cachedDuration);
    return;
  }

  // Process new URL
  let duration = null;
  let error = null;
  let source = '';

  try {
    if (isYouTubeUrl(url)) {
      duration = await getYouTubeDuration(url);
      source = 'YouTube';
    } else {
      duration = await getGenericVideoDuration(url);
      source = 'Generic';
    }
    
    // Cache the result
    cache.set(url, duration);
    cache.save();
    
  } catch (err) {
    error = err.message;
  }

  progressTracker.logProgress(url, duration, source, error);
}

function delay(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

// Main execution function
async function processVideoLinks(links) {
  if (!Array.isArray(links) || links.length === 0) {
    console.log('No links provided or invalid links array');
    return;
  }

  const cache = new VideoCache();
  cache.load();

  const progressTracker = new ProgressTracker(links.length);

  for (const url of links) {
    await processSingleUrl(url, cache, progressTracker);
    await delay(CONFIG.REQUEST_DELAY);
  }

  progressTracker.printSummary();
}


