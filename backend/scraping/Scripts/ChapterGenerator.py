import numpy as np
import json
from transformers import AutoTokenizer, AutoModel
from sklearn.cluster import KMeans
from datetime import timedelta

# Load a pre-trained model for sentence embeddings
model_name = "sentence-transformers/all-MiniLM-L6-v2"
tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModel.from_pretrained(model_name)
dir_route = "C:\\Users\\damorena\\_Modulos\\Facu\\_presente\\ProyectoDeGrado\\ProyectoDeGrado\\DB\\Transcripciones\\ad\\comp1-2024\\autochapters\\"
text_routes=["C:\\Users\\damorena\\_Modulos\\Facu\\_presente\\ProyectoDeGrado\\ProyectoDeGrado\\DB\\Transcripciones\\ad\\comp1-2024\\comp1-2024_01_medium.json","C:\\Users\\damorena\\_Modulos\\Facu\\_presente\\ProyectoDeGrado\\ProyectoDeGrado\\DB\\Transcripciones\\ad\\comp1-2024\\comp1-2024_02_medium.json"]
def embed_text(text):
    inputs = tokenizer(text, return_tensors="pt", padding=True, truncation=True)
    outputs = model(**inputs)
    return outputs.last_hidden_state.mean(dim=1).detach().numpy()
def generate_autochapter(text_route):
    with open(text_route, "r") as file:
        transcription = json.load(file)
    segments = transcription["segments"]
    texts = [segment["text"] for segment in segments]
    embeddings = np.vstack([embed_text(text) for text in texts])
    n_clusters = 3  # Adjust this number based on content length
    kmeans = KMeans(n_clusters=n_clusters, random_state=0)
    labels = kmeans.fit_predict(embeddings)

# Step 3: Generate chapters with start and end times
    chapters = []

    for cluster in range(n_clusters):
        # Extract segments for each cluster (chapter)
        chapter_segments = [segments[i] for i in range(len(labels)) if labels[i] == cluster]

        # Determine the start and end times for each chapter
        start_time = chapter_segments[0]["start"]
        end_time = chapter_segments[-1]["end"]
        # Generate a title based on a representative segment's text (e.g., central or first segment)
        title_text = chapter_segments[len(chapter_segments) // 2]["text"]  # Central segment

        # Format the chapter with autogenerated start, end, and title
        chapters.append({
            "title": title_text,
            "start_time": str(timedelta(seconds=int(start_time))),
            "end_time": str(timedelta(seconds=int(end_time)))
        })
    return chapters

autochapter1=generate_autochapter(text_routes[0])
autochapter2=generate_autochapter(text_routes[1])
